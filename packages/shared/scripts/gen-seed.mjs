const videoRows = [];
const zoneCells = { belleville: new Set(), batignolles: new Set(), butte: new Set() };
let vn = 0;
const residents = users.filter((u) => !u.role && !u.mod);

function addVideo({ author, hood, category, status = 'active', ageMin, lifeH }) {
  vn += 1;
  const r = 700 * Math.sqrt(rand());
  const theta = rand() * 2 * Math.PI;
  const lat = hood.lat + (r * Math.cos(theta)) / 111_320;
  const lng = hood.lng + (r * Math.sin(theta)) / (111_320 * Math.cos((hood.lat * Math.PI) / 180));
  const cell = latLngToCell(lat, lng, ZONE_RES);
  zoneCells[hood.key].add(cell);
  const clip = clipFor[category];
  const hasFiles = status === 'active' || status === 'hidden';
  videoRows.push({
    id: vid(vn),
    author: uuid(author.n),
    category,
    caption: pick(captions[category]),
    lat,
    lng,
    accuracy: Math.round(5 + rand() * 30),
    cell,
    rt: latLngToCell(lat, lng, RT_RES),
    status,
    merchant: category === 'shop',
    ageMin,
    lifeH: lifeH ?? lifetimeHours[category],
    video: hasFiles ? `demo/clip-${clip}.mp4` : null,
    poster: hasFiles ? `demo/clip-${clip}.jpg` : null,
  });
  return vid(vn);
}

