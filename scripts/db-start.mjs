// `pnpm db:start`: local Supabase + env files + worker container + demo media.
// Idempotent: existing env files are never overwritten.
import { execFileSync, spawnSync } from 'node:child_process';
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const isWin = process.platform === 'win32';
const run = (cmd, args, opts = {}) => {
  const res = spawnSync(cmd, args, { cwd: root, stdio: 'inherit', shell: isWin, ...opts });
  if (res.status !== 0) throw new Error(`${cmd} ${args.join(' ')} failed (${res.status})`);
};

console.log('▶ Starting local Supabase…');
run('pnpm', ['exec', 'supabase', 'start', '-x', 'imgproxy,edge-runtime,logflare,vector,supavisor']);
// `supabase start` reuses an existing volume without applying newer migrations.
run('pnpm', ['exec', 'supabase', 'migration', 'up', '--local']);

const raw = execFileSync('pnpm', ['exec', 'supabase', 'status', '-o', 'json'], {
  cwd: root,
  shell: isWin,
  encoding: 'utf8',
});
const status = JSON.parse(raw.slice(raw.indexOf('{'), raw.lastIndexOf('}') + 1));

/** VAPID keys are P-256 key pairs encoded as base64url (public key in uncompressed form). */
function vapidKeys() {
  const { publicKey, privateKey } = generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
  const pub = publicKey.export({ format: 'jwk' });
  const priv = privateKey.export({ format: 'jwk' });
  const point = Buffer.concat([
    Buffer.from([4]),
    Buffer.from(pub.x, 'base64url'),
    Buffer.from(pub.y, 'base64url'),
  ]);
  return { publicKey: point.toString('base64url'), privateKey: priv.d };
}

const webEnv = resolve(root, 'apps/web/.env.local');
const rootEnv = resolve(root, '.env');
if (!existsSync(webEnv) || !existsSync(rootEnv)) {
  const vapid = vapidKeys();
  const lines = [
    '# Generated by `pnpm db:start` for LOCAL development only. Not for production.',
    `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${status.ANON_KEY}`,
    'NEXT_PUBLIC_SITE_URL=http://localhost:3000',
    'NEXT_PUBLIC_MAP_STYLE_URL=https://tiles.openfreemap.org/styles/liberty',
    `NEXT_PUBLIC_VAPID_PUBLIC_KEY=${vapid.publicKey}`,
    `SUPABASE_URL=${status.API_URL}`,
    `SUPABASE_SERVICE_ROLE_KEY=${status.SERVICE_ROLE_KEY}`,
    `DATABASE_URL=${status.DB_URL}`,
    `VAPID_PRIVATE_KEY=${vapid.privateKey}`,
    'VAPID_SUBJECT=mailto:contact@example.org',
    `IP_HASH_SALT=${randomBytes(24).toString('hex')}`,
    'WORKER_CONCURRENCY=1',
    'FACE_BLUR_ENABLED=true',
    'FACE_MODEL_PATH=models/face_detection_yunet_2023mar.onnx',
    'PLATE_BLUR_ENABLED=false',
    'PLATE_MODEL_DIR=./models/plates',
    'PLATE_MODEL_PATH=../../models/plates/model.onnx',
  ];
  const content = lines.join('\n') + '\n';
  if (!existsSync(webEnv)) writeFileSync(webEnv, content);
  if (!existsSync(rootEnv)) writeFileSync(rootEnv, content);
  console.log('✔ Wrote apps/web/.env.local and .env');
} else if (!readFileSync(webEnv, 'utf8').includes(status.ANON_KEY)) {
  console.warn(
    '⚠ apps/web/.env.local does not match the running Supabase keys: delete it and rerun.',
  );
}

if (process.env.SKIP_WORKER !== '1') {
  console.log('▶ Building and starting the media worker (first build takes a few minutes)…');
  const workerSupabaseUrl = new URL(status.API_URL);
  workerSupabaseUrl.hostname = 'host.docker.internal';
  const workerDatabaseUrl = new URL(status.DB_URL);
  workerDatabaseUrl.hostname = 'host.docker.internal';
  run('docker', ['compose', 'up', '-d', '--build', 'worker'], {
    env: {
      ...process.env,
      WORKER_SUPABASE_URL: workerSupabaseUrl.toString(),
      WORKER_DATABASE_URL: workerDatabaseUrl.toString(),
    },
  });
}

console.log('▶ Uploading demo media…');
run('node', ['scripts/seed-media.mjs']);

console.log(`
✔ Ready.
  Web:      pnpm dev  →  http://localhost:3000
  Mailpit:  ${status.MAILPIT_URL ?? status.INBUCKET_URL}  (confirmation and recovery emails)
  Studio:   ${status.STUDIO_URL ?? 'disabled'}
  Demo accounts: lea@neighbors.test, modo.belleville@neighbors.test, admin@neighbors.test,
                 boulangerie@neighbors.test (see README)
`);
